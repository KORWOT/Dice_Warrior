using System.Diagnostics;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using DiceWarrior.SymbolLoop;
using Newtonsoft.Json;

namespace DiceWarrior.BalanceSim;

public static class Program
{
    public static int Main(string[] args)
    {
        try { return Execute(args); }
        catch (Exception e) when (e is ArgumentException or IOException or JsonException or InvalidOperationException or FormatException or OverflowException)
        {
            Console.Error.WriteLine($"BLOCKED: {e.GetType().Name}: {e.Message}");
            return 2;
        }
    }

    static int Execute(string[] args)
    {
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        var allowed = new[] { "--repo", "--output", "--count", "--master-seed", "--seeds", "--max-commands", "--timeout-seconds", "--verify" };
        if (args.Length % 2 != 0) throw new ArgumentException("Arguments require name/value pairs.");
        for (int i = 0; i < args.Length; i += 2)
            if (!allowed.Contains(args[i]) || !values.TryAdd(args[i], args[i + 1])) throw new ArgumentException("Unknown or repeated argument.");
        string Value(string key, string fallback) => values.TryGetValue(key, out var value) ? value : fallback;
        if (!values.ContainsKey("--output")) throw new ArgumentException("--output is required, beneath artifacts/balance-sim.");
        var repo = Path.GetFullPath(Value("--repo", Environment.CurrentDirectory));
        var count = int.Parse(Value("--count", "3"), CultureInfo.InvariantCulture);
        var master = uint.Parse(Value("--master-seed", BalanceScenario.DefaultMasterSeed.ToString(CultureInfo.InvariantCulture)), CultureInfo.InvariantCulture);
        var verify = bool.Parse(Value("--verify", "false"));
        uint[] seeds;
        if (values.TryGetValue("--seeds", out string seedFile))
        {
            if (values.ContainsKey("--master-seed")) throw new ArgumentException("Use --seeds or --master-seed, not both.");
            seeds = LoopJson.Decode<uint[]>(File.ReadAllText(seedFile));
            if (seeds == null || seeds.Length != count) throw new ArgumentException("Seed file must contain exactly --count seeds.");
            master = 0; // Explicit list: no claim that these were generated by this CLI.
        }
        else seeds = BalanceScenario.GenerateSeeds(master, count);
        var scenario = new BalanceScenario {
            MaxCommands = int.Parse(Value("--max-commands", "2048"), CultureInfo.InvariantCulture),
            MatchTimeoutSeconds = double.Parse(Value("--timeout-seconds", "30"), CultureInfo.InvariantCulture)
        };
        var definition = scenario.LoadDefinition(Path.Combine(repo, "Assets/_Project/Features/SharedWorld/Content/shared-world-preview-4.json"));
        scenario.Validate(definition, seeds);
        var manifest = new ScenarioManifest {
            GitSha = GitSha(repo), RulesVersion = definition.rulesVersion, ContentSha256 = BalanceScenario.ContentSha256,
            ScenarioId = scenario.ScenarioId, PolicyId = scenario.PolicyId, MasterSeed = master, Seeds = seeds,
            SeedSetSha256 = BalanceScenario.SeedHash(seeds), Heroes = scenario.Heroes,
            StartingDie = scenario.Profile.startingDie, StartingWeapon = scenario.Profile.startingWeapon, Growth = scenario.Profile.growth,
            RunnerSourceSha256 = SourceHash(repo), Runtime = System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription,
            Os = System.Runtime.InteropServices.RuntimeInformation.OSDescription, ProcessorCount = Environment.ProcessorCount,
            MaxCommands = scenario.MaxCommands, MatchTimeoutSeconds = scenario.MatchTimeoutSeconds,
            CreatedUtc = DateTime.UtcNow.ToString("O", CultureInfo.InvariantCulture),
            SeedGenerator = master == 0 ? "explicit-seed-file" : "xorshift32-13-17-5-v1; prefix stages"
        };
        string output = BalanceScenario.PrepareOutput(repo, Path.GetFullPath(values["--output"], repo));
        WriteNew(Path.Combine(output, "manifest.json"), manifest);
        WriteNew(Path.Combine(output, "seeds.json"), seeds);
        var batch = new BatchResult { Manifest = manifest, RequestedMatches = seeds.Length * scenario.Heroes.Length, Status = "PASS" };
        var checks = new List<object>();
        long allocated = GC.GetTotalAllocatedBytes();
        int[] collections = Enumerable.Range(0, 3).Select(GC.CollectionCount).ToArray();
        var clock = Stopwatch.StartNew();
        double verificationSeconds = 0;
        using (var raw = new StreamWriter(new FileStream(Path.Combine(output, "matches.jsonl"), FileMode.CreateNew), new UTF8Encoding(false)))
        {
            foreach (uint seed in seeds)
            {
                foreach (string hero in scenario.Heroes)
                {
                    var execution = MatchRunner.Run(definition, scenario, seed, hero);
                    batch.Matches.Add(execution.Result);
                    raw.WriteLine(LoopJson.Encode(execution.Result)); raw.Flush();
                    batch.Performance.MaxObservedManagedHeapBytes = Math.Max(batch.Performance.MaxObservedManagedHeapBytes, GC.GetTotalMemory(false));
                    if (execution.Result.Status != "PASS")
                    {
                        batch.Status = "BLOCKED";
                        WriteNew(Path.Combine(output, "failed-replay.json"), new { seed, hero, manifest, execution.Result.Failure, execution.Commands });
                        break;
                    }
                    if (verify)
                    {
                        var verificationClock = Stopwatch.StartNew();
                        var repeated = MatchRunner.Run(definition, scenario, seed, hero);
                        var replayed = MatchRunner.Replay(definition, scenario, seed, hero, execution.Commands);
                        var restored = MatchRunner.Run(definition, scenario, seed, hero, new RunOptions { RestoreAfterCommands = new[] { 1, 5, 10, 20 } });
                        var unobserved = MatchRunner.Run(definition, scenario, seed, hero, new RunOptions { Observe = false });
                        string basis = DeterministicResult(execution.Result);
                        bool pass = new[] { repeated, replayed, restored }.All(e => e.Result.Status == "PASS" && DeterministicResult(e.Result) == basis) &&
                            unobserved.Result.Status == "PASS" && unobserved.Result.StateHash == execution.Result.StateHash &&
                            unobserved.Result.RngHash == execution.Result.RngHash && unobserved.Result.CommandHash == execution.Result.CommandHash &&
                            LoopJson.Encode(unobserved.Result.Participants) == LoopJson.Encode(execution.Result.Participants);
                        checks.Add(new { seed, hero, Status = pass ? "PASS" : "BLOCKED", execution.Result.StateHash, execution.Result.RngHash, execution.Result.CommandHash,
                            Checks = new[] { "repeat-metrics", "command-replay", "restore-1-5-10-20", "observer-off" } });
                        verificationSeconds += verificationClock.Elapsed.TotalSeconds;
                        if (!pass)
                        {
                            batch.Status = "BLOCKED";
                            WriteNew(Path.Combine(output, "failed-verification.json"), new { seed, hero, execution.Commands, Basis = execution.Result,
                                Repeat = repeated.Result, Replay = replayed.Result, Restored = restored.Result, ObserverOff = unobserved.Result });
                            break;
                        }
                    }
                }
                if (batch.Matches.Count % 300 == 0 || batch.Status != "PASS")
                    Console.WriteLine($"{batch.Matches.Count}/{batch.RequestedMatches} matches; {clock.Elapsed.TotalSeconds:F1}s; {batch.Status}");
                if (batch.Status != "PASS") break;
            }
        }
        clock.Stop();
        using var process = Process.GetCurrentProcess(); process.Refresh();
        batch.Performance.ElapsedSeconds = clock.Elapsed.TotalSeconds - verificationSeconds;
        batch.Performance.MatchesPerSecond = batch.Matches.Count / Math.Max(batch.Performance.ElapsedSeconds, 0.000001);
        batch.Performance.MatchP50Ms = Percentile(batch.Matches.Select(m => m.ElapsedMs), .5);
        batch.Performance.MatchP95Ms = Percentile(batch.Matches.Select(m => m.ElapsedMs), .95);
        batch.Performance.PeakWorkingSetBytes = process.PeakWorkingSet64;
        batch.Performance.AllocatedBytes = GC.GetTotalAllocatedBytes() - allocated;
        batch.Performance.GcCollections = Enumerable.Range(0, 3).Select(i => GC.CollectionCount(i) - collections[i]).ToArray();
        batch.Performance.Sampling = verify ? "batch elapsed excludes verification; RSS/alloc/GC include verification; heap sampled after each primary match" :
            "sequential batch; process peak RSS; managed heap sampled after each match; GC/alloc are batch deltas";
        batch.Performance.RawOutputBytesBeforeReports = OutputBytes(output);
        WriteNew(Path.Combine(output, "verification.json"), new { Requested = verify ? batch.RequestedMatches : 0, Completed = checks.Count, VerificationSeconds = verificationSeconds, Results = checks });
        var summary = ReportWriter.Write(output, batch);
        WriteNew(Path.Combine(output, "performance.json"), new { batch.Performance, OutputBytesBeforeThisFile = OutputBytes(output), WallSeconds = clock.Elapsed.TotalSeconds });
        var hashes = Directory.GetFiles(output).OrderBy(Path.GetFileName, StringComparer.Ordinal)
            .Select(p => new { File = Path.GetFileName(p), Bytes = new FileInfo(p).Length, Sha256 = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(p))) }).ToArray();
        WriteNew(Path.Combine(output, "files.json"), hashes);
        Console.WriteLine($"{summary.Status}: completed={summary.SuccessfulMatches}/{summary.RequestedMatches}, failed={summary.FailedMatches}, notRun={summary.NotRunMatches}; output={output}");
        return batch.Status == "PASS" && summary.Status == "PASS" ? 0 : 1;
    }

    static string DeterministicResult(MatchResult result)
    {
        var copy = LoopJson.Copy(result); copy.ElapsedMs = 0;
        return LoopJson.Encode(copy);
    }
    static double Percentile(IEnumerable<double> values, double p)
    {
        var sorted = values.OrderBy(x => x).ToArray();
        return sorted.Length == 0 ? 0 : sorted[Math.Max(0, (int)Math.Ceiling(p * sorted.Length) - 1)];
    }
    static long OutputBytes(string path) => Directory.GetFiles(path).Sum(p => new FileInfo(p).Length);
    static void WriteNew(string path, object value)
    {
        using var writer = new StreamWriter(new FileStream(path, FileMode.CreateNew), new UTF8Encoding(false));
        writer.Write(JsonConvert.SerializeObject(value, Formatting.Indented)); writer.WriteLine();
    }
    static string SourceHash(string repo)
    {
        string[] dirs = { "Server/DiceWarrior.BalanceSim", "Assets/_Project/Features/SharedWorld/Domain", "Assets/_Project/Features/SymbolLoop/Domain" };
        var sources = dirs.SelectMany(d => Directory.GetFiles(Path.Combine(repo, d), "*.cs", SearchOption.TopDirectoryOnly))
            .Concat(new[] { "Server/Directory.Build.props", "Server/global.json", "Server/DiceWarrior.BalanceSim/DiceWarrior.BalanceSim.csproj",
                "Server/DiceWarrior.Competition.Shared/DiceWarrior.Competition.Shared.csproj", "Server/DiceWarrior.Shared/DiceWarrior.Shared.csproj", "Server/DiceWarrior.BalanceSim/packages.lock.json" }.Select(p => Path.Combine(repo, p)))
            .OrderBy(p => Path.GetRelativePath(repo, p).Replace('\\', '/'), StringComparer.Ordinal);
        return LoopJson.Hash(string.Join("\n", sources.Select(p => Path.GetRelativePath(repo, p).Replace('\\', '/') + ":" + Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(p))))));
    }
    static string GitSha(string repo)
    {
        var info = new ProcessStartInfo("git") { WorkingDirectory = repo, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true };
        info.ArgumentList.Add("rev-parse"); info.ArgumentList.Add("HEAD");
        using var process = Process.Start(info) ?? throw new InvalidOperationException("Cannot inspect Git HEAD.");
        string sha = process.StandardOutput.ReadToEnd().Trim(); process.WaitForExit();
        if (process.ExitCode != 0 || sha.Length != 40 || !sha.All(Uri.IsHexDigit)) throw new InvalidOperationException("Cannot establish Git HEAD.");
        return sha;
    }
}
